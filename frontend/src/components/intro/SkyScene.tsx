import React, { useEffect } from "react";
import { StyleSheet, View } from "react-native";
import { Image } from "expo-image";
import { LinearGradient } from "expo-linear-gradient";
import Animated, { Easing, useAnimatedStyle, useSharedValue, withDelay, withRepeat, withSpring, withTiming } from "react-native-reanimated";
import { KIND_COLORS } from "@/src/components/map/pins";
import { AppText } from "@/src/ui";

/**
 * App-open backdrop: a clean open sky over Lagos homes and the Lagos skyline (Eko Atlantic towers, the
 * Lekki–Ikoyi bridge), with a handful of property price markers popping up over the rooftops.
 *
 * The artwork (assets/images/intro-skyline.webp, generated by backend/scripts/gen_intro_skyline.py) is a
 * square whose top third fades to transparency, so it blends into the gradient sky on any screen size.
 * The SKY_* colours were sampled from the artwork at the blend edge.
 */
const SKYLINE = require("../../../assets/images/intro-skyline.webp");
export const SKY_TOP = "#93D4EF";
export const SKY_BLEND = "#CBE6EB";
export const SKY_HORIZON = "#F2EADE";

type Marker = { x: number; y: number; label: string; kind: keyof typeof KIND_COLORS; delay: number };
/** Positions are fractions of the square artwork (x →, y ↓); the marker's caret tip lands on the point. */
const MARKERS: Marker[] = [
  { x: 0.17, y: 0.79, label: "₦185M", kind: "sale", delay: 450 },
  { x: 0.47, y: 0.75, label: "₦95M", kind: "sale", delay: 620 },
  { x: 0.82, y: 0.73, label: "₦4.5M/yr", kind: "rent", delay: 790 },
  { x: 0.62, y: 0.655, label: "₦250M", kind: "sale", delay: 960 },
  { x: 0.30, y: 0.655, label: "₦180k/night", kind: "shortlet", delay: 1130 },
];
const MARKER_W = 132;
const MARKER_H = 40;

/** Share of the screen height the artwork must cover so the skyline reads on tall phones and tablets alike. */
export function skylineBox(width: number, height: number) {
  const size = Math.max(width, Math.round(height * 0.55));
  return { size, left: Math.round((width - size) / 2), top: height - size };
}

export function SkyScene({ width, height, reduceMotion = false }: { width: number; height: number; reduceMotion?: boolean }) {
  const box = skylineBox(width, height);
  return (
    <View style={StyleSheet.absoluteFill} pointerEvents="none" testID="intro-sky-scene">
      <LinearGradient colors={[SKY_TOP, SKY_BLEND, SKY_HORIZON]} locations={[0, 0.62, 1]} style={StyleSheet.absoluteFill} />
      <Image source={SKYLINE} style={{ position: "absolute", left: box.left, top: box.top, width: box.size, height: box.size }} contentFit="cover" transition={reduceMotion ? 0 : 350} accessibilityLabel="Lagos homes and skyline under an open sky" />
      {MARKERS.map((m) => (
        <PopMarker key={m.label} marker={m} left={box.left + m.x * box.size - MARKER_W / 2} top={box.top + m.y * box.size - MARKER_H} reduceMotion={reduceMotion} />
      ))}
    </View>
  );
}

/** A map-style price pill that drops in with a spring, then floats gently. */
function PopMarker({ marker, left, top, reduceMotion }: { marker: Marker; left: number; top: number; reduceMotion: boolean }) {
  const pop = useSharedValue(reduceMotion ? 1 : 0);
  const bob = useSharedValue(0);
  useEffect(() => {
    if (reduceMotion) return;
    pop.value = withDelay(marker.delay, withSpring(1, { damping: 13, stiffness: 190, mass: 0.7 }));
    bob.value = withDelay(marker.delay + 600, withRepeat(withTiming(1, { duration: 1900 + (marker.delay % 300), easing: Easing.inOut(Easing.sin) }), -1, true));
  }, [reduceMotion, marker.delay, pop, bob]);
  const anim = useAnimatedStyle(() => ({
    opacity: Math.min(1, pop.value * 1.4),
    transform: [{ translateY: (1 - pop.value) * -14 + bob.value * 3 }, { scale: 0.6 + 0.4 * pop.value }],
  }));
  const tint = KIND_COLORS[marker.kind];
  return (
    <Animated.View style={[styles.marker, { left, top }, anim]} testID={`intro-marker-${marker.kind}`}>
      <View style={[styles.pill, { backgroundColor: tint }]}>
        <AppText color="#FFFFFF" tabular numberOfLines={1} style={styles.price}>
          {marker.label}
        </AppText>
      </View>
      <View style={[styles.caret, { borderTopColor: tint }]} />
    </Animated.View>
  );
}

const styles = StyleSheet.create({
  marker: { position: "absolute", width: MARKER_W, height: MARKER_H, alignItems: "center", justifyContent: "flex-end" },
  pill: { height: 30, paddingHorizontal: 11, borderRadius: 999, borderWidth: 1.5, borderColor: "#FFFFFF", alignItems: "center", justifyContent: "center", shadowColor: "#000", shadowOpacity: 0.22, shadowRadius: 6, shadowOffset: { width: 0, height: 3 }, elevation: 4 },
  price: { fontFamily: "PlusJakartaSans-800", fontSize: 14.5, lineHeight: 18, letterSpacing: -0.2 },
  caret: { width: 0, height: 0, borderLeftWidth: 7, borderRightWidth: 7, borderTopWidth: 7, borderLeftColor: "transparent", borderRightColor: "transparent", marginTop: -1 },
});
